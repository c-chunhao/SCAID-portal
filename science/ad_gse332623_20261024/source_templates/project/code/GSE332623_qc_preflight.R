args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) == 2L)
.libPaths(c('@R_LIB@', .libPaths()))
suppressPackageStartupMessages({library(Seurat); library(Matrix); library(jsonlite); library(ggplot2)})
manifest <- read.delim('@PROJECT@/00.corrected_analysis/GSE332623/capture_manifest.tsv', check.names = FALSE)
entry <- manifest[manifest$library_id == args[1], , drop = FALSE]; stopifnot(nrow(entry) == 1L)
out <- args[2]; dir.create(out, recursive = TRUE, showWarnings = FALSE)
stopifnot(digest::digest(entry$input_rds, algo = 'sha256', file = TRUE) == entry$input_sha256)
s <- readRDS(entry$input_rds)
r <- GetAssayData(s, assay = 'RNA', layer = 'counts'); a <- GetAssayData(s, assay = 'ADT', layer = 'counts')
fm <- s[['RNA']][[]]; symbols <- as.character(fm$source_symbol)
stopifnot(identical(colnames(r), colnames(a)), identical(rownames(fm), rownames(r)))
umi <- Matrix::colSums(r); genes <- Matrix::colSums(r > 0)
mt <- grepl('^MT-', symbols, ignore.case = FALSE); ribo <- grepl('^RP[SL][0-9]', symbols); hb <- grepl('^HB[ABDEGMQZ]', symbols)
fraction <- function(index) if (any(index)) 100 * Matrix::colSums(r[index, , drop = FALSE]) / pmax(umi, 1) else rep(0, length(umi))
df <- data.frame(cell_id = colnames(r), nCount_RNA = umi, nFeature_RNA = genes,
                 percent_mt = fraction(mt), percent_ribo = fraction(ribo), percent_hb = fraction(hb),
                 nCount_ADT = Matrix::colSums(a), nFeature_ADT = Matrix::colSums(a > 0),
                 row.names = colnames(r), stringsAsFactors = FALSE)
stats <- lapply(df[, -1], function(x) quantile(x, c(0, .001, .005, .01, .025, .05, .1, .25, .5, .75, .9, .95, .975, .99, .995, .999, 1)))
robust <- lapply(list(UMI = log10(umi + 1), genes = log10(genes + 1), mt = df$percent_mt), function(x) list(median = median(x), mad = mad(x), low_3MAD = median(x) - 3 * mad(x), high_4MAD = median(x) + 4 * mad(x)))
write_json(list(library = args[1], source_sha256 = entry$input_sha256, n_barcodes = ncol(r), RNA_features = nrow(r), ADT_features = nrow(a), mt_gene_count = sum(mt), mt_gene_symbols = symbols[mt], statistics = stats, robust_statistics = robust, source_metadata_fields = colnames(s[[]]), feature_fields = colnames(fm)), file.path(out, 'preflight.json'), auto_unbox = TRUE, digits = NA, pretty = TRUE)
saveRDS(df, file.path(out, 'metrics.rds'))
saveRDS(fm, file.path(out, 'feature_metadata.rds'))
for (metric in c('nCount_RNA', 'nFeature_RNA', 'percent_mt', 'percent_ribo', 'percent_hb')) {
  d <- data.frame(value = df[[metric]])
  if (metric %in% c('nCount_RNA', 'nFeature_RNA')) d$value <- log10(d$value + 1)
  p <- ggplot(d, aes(x = value)) + geom_histogram(bins = 100, fill = '#297f86', color = 'white', linewidth = .1) + theme_classic(base_size = 12) + labs(title = args[1], x = if (metric %in% c('nCount_RNA','nFeature_RNA')) paste0('log10(', metric, ' + 1)') else metric, y = 'Source barcodes')
  ggsave(file.path(out, paste0(metric, '.png')), p, width = 7, height = 4, dpi = 150)
}
set.seed(332623); keep <- sample(seq_len(nrow(df)), min(nrow(df), 10000L))
p <- ggplot(df[keep, ], aes(x = nCount_RNA, y = nFeature_RNA, color = percent_mt)) + geom_point(size = .3, alpha = .6) + scale_x_log10() + scale_y_log10() + scale_color_viridis_c() + theme_classic(base_size = 12) + labs(title = args[1])
ggsave(file.path(out, 'UMI_genes_mt.png'), p, width = 7, height = 5, dpi = 150)
cat('Preflight metrics complete:', args[1], ncol(r), 'barcodes\n')
